"""Export the 18-dim geometric basis as a C-runtime scheme file.

src/vectors.h is generated, not edited: tools/data/spec_next.scheme goes
through tools/gen_vectors_h.py into the static table both binaries compile.
So moving the runtime onto the tongue-contour basis is a data change, not a
code change -- but only if the basis can be written in the scheme's own
format, and the weights are not hand-tuned a second time.

The weights come from the gate's own fitter (gate_retrieval.fit_metric, same
objective and regularisation the LOCO audit uses), averaged over the nine
SVMCC language folds. Averaging per-fold weights rather than fitting once on
all 133 symbols keeps the exported vector from encoding any single fold's
segment inventory. These are still FITTED weights, not a validated scheme:
what LOCO measures is the metric fitted on training folds only, and this file
cannot express that distinction, so the number to quote remains the LOCO one.

Airstream codes are carried over from src/vectors.h rather than re-derived:
gen_tongue_table.py has no notion of click airstream, and inventing one would
put a hand-assigned column next to a mechanically generated one.

Run: python tools/export_tongue_scheme.py
"""

import io
import json
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gate_retrieval as G            # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'tools', 'data')
BASIS = os.path.join(DATA, 'merged_basis.json')
VECTORS_H = os.path.join(ROOT, 'src', 'vectors.h')
SCHEME_OLD = os.path.join(DATA, 'spec_next.scheme')
OUT = os.path.join(DATA, 'tongue.scheme')
NDM_OLD = 16

LAM = G.LAMBDA if hasattr(G, 'LAMBDA') else 5.5


def airstream_codes():
    """Per-symbol airstream NAME, taken from the committed scheme.

    src/vectors.h stores an integer index but the scheme format wants a name,
    and this exporter previously wrote the raw digit -- the loader then
    rejected all 133 rows with "unknown airstream '0'". Reading the names from
    the committed scheme instead of re-deriving them from the index removes the
    index-to-name mapping from this file entirely, so there is no order to get
    wrong and no way to silently transpose ejective with implosive.
    """
    out = {}
    for ln in io.open(SCHEME_OLD, encoding='utf-8'):
        t = ln.split()
        if t and t[0] == 'seg':
            out[t[1]] = t[2 + NDM_OLD]
    return out


def fit_weights(X, syms, feats, per_lang):
    """Average the gate's own diagonal metric over the LOCO folds."""
    order = {s: i for i, s in enumerate(syms)}
    n = len(syms)
    F = np.zeros((n, len(next(iter(feats.values())))))
    for s, v in feats.items():
        F[order[s]] = v

    logs = []
    for held in G.SVMCC:
        train = sorted(set().union(*[set(per_lang[l]) for l in G.SVMCC
                                     if l != held]) - set(per_lang[held]))
        if len(train) < G.MIN_TRAIN:
            continue
        ref = np.array([order[s] for s in train])
        Ftrain = [order[s] for s in train if s in feats]
        w, _, _ = G.fit_metric(X, F, Ftrain, ref)
        logs.append(w)
    if not logs:
        raise SystemExit('no LOCO fold produced a metric')
    mean_log = np.mean(logs, axis=0)
    return mean_log, len(logs)


def main():
    basis = json.load(io.open(BASIS, encoding='utf-8'))
    dims, table = basis['dims'], basis['table']
    syms = sorted(table)
    X = np.array([table[s] for s in syms], float)

    rank = np.linalg.matrix_rank(X)
    if rank < len(dims):
        raise SystemExit('basis is rank %d of %d -- a zero-variance axis would '
                         'get an arbitrary weight' % (rank, len(dims)))

    air = airstream_codes()
    missing = [s for s in syms if s not in air]
    if missing:
        raise SystemExit('no airstream code for %s' % missing)

    wanted = set(syms)
    feats, _, _, _ = G.load_phoible(wanted)
    per_lang, _ = G.load_svmcc_tokens(wanted)
    mean_log, nfold = fit_weights(X, syms, feats, per_lang)
    w = np.exp(mean_log - mean_log.max())
    w = w / w.max()

    lines = ['# 18-dim tongue-contour basis, generated by '
             'tools/export_tongue_scheme.py from merged_basis.json.',
             '# Weights are the gate fitter averaged over %d LOCO folds; they '
             'are FITTED, not a validated scheme.' % nfold,
             '# Do not hand-edit -- re-run the exporter instead.',
             'ndim %d' % len(dims)]
    lines += ['dim %s' % d for d in dims]
    lines.append('weight ' + ' '.join('%.6f' % x for x in w))
    lines.append('lambda %.4f' % LAM)
    for s in syms:
        lines.append('seg %s %s %s'
                     % (s, ' '.join('%.4f' % x for x in table[s]), air[s]))

    with io.open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')

    print('wrote %s' % OUT)
    print('  %d dims, %d segments, rank %d/%d' % (len(dims), len(syms), rank,
                                                  len(dims)))
    print('  distinct vectors %d of %d' % (len({tuple(table[s])
                                                for s in syms}), len(syms)))
    print('  weights from %d LOCO folds, range %.4f .. %.4f'
          % (nfold, w.min(), w.max()))
    print('\n  %-18s %8s' % ('axis', 'weight'))
    for d, x in sorted(zip(dims, w), key=lambda p: -p[1]):
        print('  %-18s %8.4f' % (d, x))
    print('\nnext: python tools/gen_vectors_h.py --scheme %s' % OUT)


if __name__ == '__main__':
    main()